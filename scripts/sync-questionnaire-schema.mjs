// Copies the client dashboard's questionnaire schema into Forma as plain JavaScript.
// The dashboard (repo toggle-concepts) owns the questions; their ids are the contract (docs/contract.md there).
// Usage: node scripts/sync-questionnaire-schema.mjs [path to toggle-concepts]   (default: ../toggle-concepts)
// test/questionnaire-schema.test.mjs fails when the copy and the dashboard's file drift apart.
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import * as nodeModule from 'node:module';

// Node 22.13+ strips TypeScript types itself; older versions cannot run this script.
export const canGenerate = typeof nodeModule.stripTypeScriptTypes === 'function';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
export const OUT = path.join(root, 'shared', 'questionnaire-schema.mjs');
export const defaultDashboard = () => process.env.DASHBOARD_REPO || path.resolve(root, '..', 'toggle-concepts');

export async function generate(dashboard = defaultDashboard()) {
  const src = await fs.readFile(path.join(dashboard, 'questionnaire', 'schema.ts'), 'utf8');
  if (!canGenerate) throw Error('Node 22.13 or newer is needed to copy the questionnaire schema.');
  const js = nodeModule.stripTypeScriptTypes(src, {mode: 'strip'});
  return '// GENERATED by scripts/sync-questionnaire-schema.mjs from toggle-concepts/questionnaire/schema.ts. Do not edit.\n'
    + '// Re-run the script after the dashboard changes its questions.\n' + js.replace(/[ \t]+$/gm, '').replace(/\n{3,}/g, '\n\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = await generate(process.argv[2] || defaultDashboard());
  await fs.writeFile(OUT, out);
  console.log('Wrote ' + path.relative(root, OUT));
}
